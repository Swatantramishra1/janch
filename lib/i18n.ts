export function isLangCode(v: string | undefined | null): v is LangCode {
  return !!v && LANGUAGES.some((l) => l.code === v);
}

export function langMeta(code: LangCode): LangMeta {
  return LANGUAGES.find((l) => l.code === code) ?? LANGUAGES[0];
}

